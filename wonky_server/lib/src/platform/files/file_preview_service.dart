/// The images of [FilePreviews.render].
class RenderedPreview {
  const RenderedPreview({
    required this.width,
    required this.height,
    this.preview,
    this.previewMime,
    this.thumbnail,
    this.thumbnailMime,
  });

  /// Size of the (EXIF-oriented) original.
  final int width;
  final int height;

  /// ≤ [FilePreviews.maxPreviewSide] px, metadata stripped; null when the
  /// image was too large to decode.
  final Uint8List? preview;
  final String? previewMime;
  final Uint8List? thumbnail;
  final String? thumbnailMime;
}

/// Pure image work of the previews (Drive 02 §6.2): bounded decoding,
/// auto-orientation by EXIF, metadata stripping, the ≤ 2048 px preview and
/// the 400 × 300 thumbnail.
abstract final class FilePreviews {
  static const maxPreviewSide = 2048;
  static const thumbWidth = 400;
  static const thumbHeight = 300;

  /// Images above this are not decoded (only their size is recorded).
  static const maxPixels = 50 * 1000 * 1000;

  static img.Decoder? _decoder(String mimeType) => switch (mimeType) {
    'image/png' => img.PngDecoder(),
    'image/jpeg' => img.JpegDecoder(),
    'image/gif' => img.GifDecoder(),
    'image/webp' => img.WebPDecoder(),
    'image/bmp' => img.BmpDecoder(),
    _ => null,
  };

  /// Renders the preview of [bytes] (sniffed [mimeType]); null when the
  /// bytes can't be decoded. Synchronous: run it in an isolate.
  static RenderedPreview? render(Uint8List bytes, String mimeType) {
    final decoder = _decoder(mimeType);
    if (decoder == null) return null;
    final info = decoder.startDecode(bytes);
    if (info == null || info.width <= 0 || info.height <= 0) return null;
    if (info.width * info.height > maxPixels) {
      return RenderedPreview(width: info.width, height: info.height);
    }
    final decoded = decoder.decode(bytes, frame: 0);
    if (decoded == null) return null;
    // Auto-orient, then drop EXIF (GPS etc.) and every other metadata.
    final oriented = img.bakeOrientation(decoded)..exif = img.ExifData();
    oriented.iccProfile = null;
    oriented.textData = null;
    final alpha = oriented.hasAlpha;
    Uint8List encode(img.Image i) =>
        alpha ? img.encodePng(i) : img.encodeJpg(i, quality: 85);
    final mime = alpha ? 'image/png' : 'image/jpeg';

    var preview = oriented;
    final longest = oriented.width > oriented.height
        ? oriented.width
        : oriented.height;
    if (longest > maxPreviewSide) {
      preview = oriented.width >= oriented.height
          ? img.copyResize(
              oriented,
              width: maxPreviewSide,
              interpolation: img.Interpolation.average,
            )
          : img.copyResize(
              oriented,
              height: maxPreviewSide,
              interpolation: img.Interpolation.average,
            );
    }
    // Cover crop to 400 × 300.
    final scale = [
      thumbWidth / oriented.width,
      thumbHeight / oriented.height,
    ].reduce((a, b) => a > b ? a : b);
    final scaledW = (oriented.width * scale).ceil().clamp(1, 1 << 20);
    final scaledH = (oriented.height * scale).ceil().clamp(1, 1 << 20);
    final scaled = img.copyResize(
      preview,
      width: scaledW,
      height: scaledH,
      interpolation: img.Interpolation.average,
    );
    final thumb = img.copyCrop(
      scaled,
      x: ((scaledW - thumbWidth) / 2).floor().clamp(0, scaledW),
      y: ((scaledH - thumbHeight) / 2).floor().clamp(0, scaledH),
      width: scaledW < thumbWidth ? scaledW : thumbWidth,
      height: scaledH < thumbHeight ? scaledH : thumbHeight,
    );
    return RenderedPreview(
      width: oriented.width,
      height: oriented.height,
      preview: encode(preview),
      previewMime: mime,
      thumbnail: encode(thumb),
      thumbnailMime: mime,
    );
  }
}

/// Server previews of uploaded images (Drive 02 §6.2, §6.6): generated by
/// a future call after `completeFileUpload` (and copies). Failures leave
/// `previewFileId`/`thumbnailFileId` null.
abstract final class FilePreviewService {
  /// Time limit of one rendering.
  static const timeLimit = Duration(seconds: 10);

  /// Schedules [generate] for an item. By default a future call without
  /// delay ([FilePreviewFutureCall]); tests replace it (inline or no-op).
  static Future<void> Function(Session session, int itemId) schedule =
      _scheduleViaFutureCall;

  static Future<void> _scheduleViaFutureCall(Session session, int itemId) =>
      session.serverpod.futureCalls
          .callWithDelay(Duration.zero)
          .filePreview
          .generate(itemId);

  /// Whether [item] gets a server preview: ready images the server can
  /// decode.
  static bool wantsPreview(DriveItem item) =>
      item.kind == DriveItemKind.file &&
      item.uploadState == FileUploadState.ready &&
      item.fileCategory == FileCategory.image &&
      FileTypes.isRenderableImage(item.mimeType ?? '');

  /// [FilePreviews.render] in its own isolate, killed after [timeLimit]
  /// (a helper, so the closure captures only the bytes and the type).
  static Future<RenderedPreview?> _render(Uint8List bytes, String mime) =>
      IsolateRunner.run(
        () => FilePreviews.render(bytes, mime),
        name: 'file-preview',
        timeout: timeLimit,
      );

  /// Generates the preview and thumbnail of file item [itemId]. Returns
  /// whether a preview was stored.
  static Future<bool> generate(Session session, int itemId) async {
    final item = await DriveItem.db.findById(session, itemId);
    if (item == null || !wantsPreview(item) || item.contentRef == null) {
      return false;
    }
    final file = await FileService.byUuid(session, item.contentRef!);
    if (file == null || file.status != StoredFileStatus.ready) return false;
    final data = await FileService.readBytes(session, file);
    final bytes = Uint8List.sublistView(data);
    final mime = item.mimeType!;
    RenderedPreview? rendered;
    try {
      rendered = await _render(bytes, mime);
    } on Object catch (e) {
      session.log(
        'Preview of item $itemId failed: $e',
        level: LogLevel.warning,
      );
      return false;
    }
    if (rendered == null) return false;
    await DriveFileService.mergeServerMeta(session, itemId, {
      'width': rendered.width,
      'height': rendered.height,
    });
    if (rendered.preview == null) {
      await _notify(session, itemId);
      return false;
    }
    final ext = rendered.previewMime == 'image/png' ? 'png' : 'jpg';
    final preview = await FileService.storeServerFile(
      session,
      ownerId: item.ownerId,
      itemId: item.id,
      kind: StoredFileKind.preview,
      fileName: 'preview.$ext',
      mimeType: rendered.previewMime!,
      bytes: rendered.preview!,
    );
    final thumb = await FileService.storeServerFile(
      session,
      ownerId: item.ownerId,
      itemId: item.id,
      kind: StoredFileKind.thumbnail,
      fileName: 'thumbnail.$ext',
      mimeType: rendered.thumbnailMime!,
      bytes: rendered.thumbnail!,
    );
    // The item may have been deleted meanwhile.
    final current = await DriveItem.db.findById(session, itemId);
    if (current == null) {
      await FileService.deleteFile(session, preview.fileUuid);
      await FileService.deleteFile(session, thumb.fileUuid);
      return false;
    }
    await DriveItem.db.updateWhere(
      session,
      columnValues: (t) => [
        t.previewFileId(preview.fileUuid),
        t.thumbnailFileId(thumb.fileUuid),
      ],
      where: (t) => t.id.equals(itemId),
    );
    for (final old in [current.previewFileId, current.thumbnailFileId]) {
      if (old != null) await FileService.deleteFile(session, old);
    }
    await _notify(session, itemId);
    return true;
  }

  static Future<void> _notify(Session session, int itemId) async {
    final item = await DriveItem.db.findById(session, itemId);
    if (item != null) {
      await DriveEvents.notify(session, item, DriveChangeKind.updated);
    }
  }
}
